// Generates src/lib/icons/mask-icons.ts: lucide icons as CSS mask images, for the
// server-rendered marketing pages.
//
//   node scripts/build-mask-icons.mjs        (re-run after adding an icon to NAMES)
//
// Why: an inline lucide <svg> is 3-7 DOM nodes and, when it comes from a client
// component, a hydration unit too. On the homepage icons were 448 of 983 DOM nodes.
// A mask icon is a single <span> whose shape is the icon and whose colour is the text
// colour, so it looks the same and costs one node and no JavaScript.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const iconsDir = path.join(root, 'node_modules/lucide-react/dist/esm/icons');

// Every icon the marketing pages render through <MaskIcon>. QR type icons come from
// the catalogue, so they are read from it rather than listed twice.
const SECTION_ICONS = [
  'ArrowRight', 'ArrowUpRight', 'BarChart3', 'Boxes', 'Building2', 'CalendarCheck', 'CalendarClock', 'Clock',
  'Code2', 'Globe2', 'Images', 'Infinity', 'Layers', 'Lock', 'Palette', 'Rocket', 'ShieldCheck', 'Smartphone',
  'Sparkles', 'Star', 'Store', 'UtensilsCrossed', 'Users', 'QrCode',
];
const catalog = fs.readFileSync(path.join(root, 'src/lib/qr/catalog.ts'), 'utf8');
const TYPE_ICONS = [...catalog.matchAll(/icon: '([A-Za-z0-9]+)'/g)].map((m) => m[1]);
const NAMES = [...new Set([...SECTION_ICONS, ...TYPE_ICONS])].sort();

// lucide-react file names are kebab-case; a few names carry digits ("bar-chart-3").
const kebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([a-zA-Z])([0-9])/g, '$1-$2')
    .toLowerCase();

function iconFile(name) {
  for (const candidate of [kebab(name), kebab(name).replace(/-(\d)/g, '$1')]) {
    const file = path.join(iconsDir, `${candidate}.js`);
    if (fs.existsSync(file)) return file;
  }
  throw new Error(`lucide icon not found: ${name}`);
}

// Renamed icons are aliases whose file only re-exports another icon's file.
function readIconSource(file, depth = 0) {
  const source = fs.readFileSync(file, 'utf8');
  if (source.includes('createLucideIcon(') || depth > 3) return source;
  const target = source.match(/from ['"](\.\/[^'"]+)['"]/)?.[1];
  if (!target) throw new Error(`cannot resolve icon file ${file}`);
  return readIconSource(path.join(path.dirname(file), target), depth + 1);
}

function svgFor(name) {
  const source = readIconSource(iconFile(name));
  const body = source.match(/createLucideIcon\("[^"]+", (\[[\s\S]*?\])\);/)[1];
  // The node list is plain data: [tag, { attr: "value", key: "…" }] — JSON after quoting keys.
  const nodes = JSON.parse(body.replace(/([{,]\s*)([a-zA-Z][\w-]*):/g, '$1"$2":'));
  const inner = nodes
    .map(([tag, attrs]) => {
      const list = Object.entries(attrs)
        .filter(([key]) => key !== 'key')
        .map(([key, value]) => `${key}="${value}"`)
        .join(' ');
      return `<${tag} ${list}/>`;
    })
    .join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`;
}

const entries = NAMES.map((name) => {
  const uri = `url("data:image/svg+xml,${encodeURIComponent(svgFor(name)).replace(/'/g, '%27')}")`;
  return `  ${JSON.stringify(name)}: ${JSON.stringify(uri)},`;
});

const out = `// Generated by scripts/build-mask-icons.mjs from lucide-react ${JSON.parse(fs.readFileSync(path.join(root, 'node_modules/lucide-react/package.json'), 'utf8')).version}. Do not edit by hand.
// Each value is a CSS url() for mask-image; see components/ui/mask-icon.tsx.
export const MASK_ICONS: Record<string, string> = {
${entries.join('\n')}
};
`;
fs.mkdirSync(path.join(root, 'src/lib/icons'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/lib/icons/mask-icons.ts'), out);
console.log(`${NAMES.length} icons -> src/lib/icons/mask-icons.ts (${Math.round(out.length / 1024)} KB)`);
